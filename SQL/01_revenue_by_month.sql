-- ============================================================
-- Запрос 01: Выручка по месяцам
-- ============================================================
-- Бизнес-задача: понять динамику выручки по месяцам,
--                выявить пики и провалы в продажах.
-- Датасет: Northwind (MySQL)
-- ============================================================

SELECT
    DATE_FORMAT(orders.order_date, '%Y-%m') AS order_month,       -- год-месяц заказа
    ROUND(SUM(order_details.quantity * order_details.unit_price), 2) AS revenue
                                                                  -- выручка: кол-во × цена
FROM orders
JOIN order_details
ON orders.id = order_details.order_id                             -- связь заказ ↔ позиции
GROUP BY order_month                                              -- группировка по месяцу
ORDER BY order_month;                                             -- сортировка от старых к новым

